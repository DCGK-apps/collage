import builtinPack from '../templates/builtin.collage-template.json';
import { pageSizeMm } from '../core/page';
import {
  applyTemplate,
  makePack,
  parseTemplateFile,
  photoOrder,
  templateFileName,
  templateFromDoc,
  templateKey,
  templateSvg,
  type Template,
} from '../core/templates';
import { TemplateStore, type StoredTemplate } from '../templates/store';
import type { Store } from '../store';
import { saveFile } from './saveFile';

interface Entry {
  key: string;
  template: Template;
  builtin: boolean;
}

const BUILTIN: Entry[] = parseTemplateFile(builtinPack).templates.map((t) => ({ key: templateKey(t), template: t, builtin: true }));

/** Save dialog where supported, share sheet on phones, download elsewhere. */
function offerFile(blob: Blob, name: string): Promise<unknown> {
  return saveFile(name, 'template', () => blob, { share: true }).catch((err) => console.error(err));
}

const jsonBlob = (data: unknown) => new Blob([JSON.stringify(data, null, 2) + '\n'], { type: 'application/json' });

/** The "Szablony" panel: gallery, apply, save current, import and export. */
export function initTemplates(store: Store, toast: (t: string) => void): void {
  const $ = (id: string) => document.getElementById(id)!;
  const list = $('template-list');
  let db: TemplateStore | null = null;
  try {
    db = 'indexedDB' in window ? new TemplateStore() : null;
  } catch {
    db = null;
  }
  let user: StoredTemplate[] = [];
  let filter: 'match' | 'all' = 'match';
  let renderedKey = '';

  const all = (): Entry[] => [
    ...user.map((u) => ({ key: u.id, template: u.template, builtin: false })),
    ...BUILTIN,
  ];
  const known = (key: string) => all().some((e) => e.key === key);

  async function reload(): Promise<void> {
    try {
      user = db ? await db.list() : [];
    } catch {
      user = [];
    }
    renderedKey = '';
    render();
  }

  function render(): void {
    const photos = photoOrder(store.doc).length;
    const key = `${photos}|${filter}|${user.map((u) => u.id).join(',')}|${store.doc.orientation}`;
    if (key === renderedKey) return;
    renderedKey = key;

    const matching = all().filter((e) => e.template.slots === photos);
    const effective = filter === 'match' && matching.length ? 'match' : 'all';
    $('tpl-filter-match').textContent = `Dla ${photos} zdjęć (${matching.length})`;
    $('tpl-filter-match').classList.toggle('active', effective === 'match');
    $('tpl-filter-all').classList.toggle('active', effective === 'all');
    const entries = effective === 'match' ? matching : all();

    list.innerHTML = '';
    for (const e of entries) {
      const t = e.template;
      const card = document.createElement('div');
      card.className = 'tpl-card';
      card.dataset.testid = 'template';
      card.dataset.key = e.key;
      card.dataset.builtin = String(e.builtin);
      const thumb = document.createElement('button');
      thumb.className = 'tpl-thumb';
      thumb.title = `Zastosuj „${t.name}”`;
      // SVG is generated by templateSvg from validated numbers only.
      thumb.innerHTML = templateSvg(t, pageSizeMm(store.doc.formatId, t.page.orientation));
      thumb.addEventListener('click', () => {
        store.edit((doc) => applyTemplate(doc, t));
        store.ui.selectedCellId = null;
        store.ui.selectedFloatId = null;
        toast(`Zastosowano szablon „${t.name}”`);
      });
      const name = document.createElement('div');
      name.className = 'tpl-name';
      name.textContent = t.name;
      const meta = document.createElement('div');
      meta.className = 'tpl-meta';
      meta.textContent = `${t.slots} ${t.slots === 1 ? 'zdjęcie' : t.slots < 5 ? 'zdjęcia' : 'zdjęć'}${e.builtin ? '' : ' · mój'}`;
      const actions = document.createElement('div');
      actions.className = 'tpl-actions';
      const exp = document.createElement('button');
      exp.className = 'mini-btn';
      exp.title = 'Eksportuj do pliku';
      exp.dataset.testid = 'template-export';
      exp.textContent = '⇩';
      exp.addEventListener('click', () => void offerFile(jsonBlob(t), templateFileName(t)));
      actions.append(exp);
      if (!e.builtin) {
        const del = document.createElement('button');
        del.className = 'mini-btn danger';
        del.title = 'Usuń szablon';
        del.dataset.testid = 'template-delete';
        del.textContent = '✕';
        del.addEventListener('click', async () => {
          await db?.delete(e.key);
          toast(`Usunięto szablon „${t.name}”`);
          await reload();
        });
        actions.append(del);
      }
      card.append(thumb, name, meta, actions);
      list.append(card);
    }
    if (!entries.length) list.innerHTML = '<p class="empty-note">Brak szablonów.</p>';
  }

  $('tpl-filter-match').addEventListener('click', () => {
    filter = 'match';
    renderedKey = '';
    render();
  });
  $('tpl-filter-all').addEventListener('click', () => {
    filter = 'all';
    renderedKey = '';
    render();
  });

  $('btn-tpl-save').addEventListener('click', async () => {
    if (!store.doc.tree && !store.doc.floats.length) {
      toast('Najpierw ułóż kolaż');
      return;
    }
    const name = window.prompt('Nazwa szablonu', `Mój układ ${user.length + 1}`);
    if (name === null) return;
    const t = templateFromDoc(store.doc, name);
    const key = templateKey(t);
    if (known(key)) {
      toast('Taki szablon już jest');
      return;
    }
    if (!db) {
      toast('Zapisywanie szablonów nie jest dostępne w tej przeglądarce');
      return;
    }
    await db.put({ id: key, template: t, createdAt: Date.now() });
    filter = 'all';
    toast(`Zapisano szablon „${t.name}”`);
    await reload();
  });

  $('btn-tpl-export-mine').addEventListener('click', () => {
    if (!user.length) {
      toast('Nie masz jeszcze własnych szablonów');
      return;
    }
    void offerFile(jsonBlob(makePack(user.map((u) => u.template))), 'moje-szablony.collage-template.json');
  });

  const input = $('file-templates') as HTMLInputElement;
  input.addEventListener('change', async () => {
    const files = Array.from(input.files ?? []);
    input.value = '';
    let added = 0;
    let skipped = 0;
    let rejected = 0;
    for (const file of files) {
      let json: unknown;
      try {
        json = JSON.parse(await file.text());
      } catch {
        rejected++;
        continue;
      }
      const res = parseTemplateFile(json);
      rejected += res.rejected;
      for (const t of res.templates) {
        const key = templateKey(t);
        if (known(key)) {
          skipped++;
          continue;
        }
        await db?.put({ id: key, template: t, createdAt: Date.now() + added });
        user.push({ id: key, template: t, createdAt: Date.now() });
        added++;
      }
    }
    const parts = [`Zaimportowano: ${added}`];
    if (skipped) parts.push(`już były: ${skipped}`);
    if (rejected) parts.push(`nieprawidłowe: ${rejected}`);
    toast(parts.join(' · '));
    filter = 'all';
    await reload();
  });

  store.subscribe(render);
  void reload();
}
